"""Shared setup for the GFS-VL 3D VLM (RegionPLC, sparseunet32_636).

Builds the text embedding (CLIP ViT-B/32, lseg template) over the GFS-VL label
space (12 base + 45 novel = 57 classes), constructs the vision network and loads
the 636 checkpoint, following `GFS_VL_Trainer.build_zero_shot_model` in
`pointcept/engines/train.py`.
"""

import os
import sys
import logging
import runpy
from pathlib import Path

import numpy as np
import torch

GFS = Path("/data01/jh/code/GFS-VL")
PLA = GFS / "pointcept/models/PLA"
REGIONPLC = Path("/data01/jh/code/GFS-VL/pointcept/models/PLA")
VLM_CFG = PLA / "tools/cfgs/scannet200_models/zs/spconv_clip_caption_openscene.yaml"
CKPT = Path("/data01/jh/code/GFS-VL/pretrain_weights/sparseunet32_636.pth")
META = GFS / "pointcept/datasets/preprocessing/scannet/meta_data"
CONSTANTS = runpy.run_path(str(META / "scannet200_constants.py"))

BASE_NAMES = list(CONSTANTS["CLASS_LABELS_BASE"])
NOVEL_NAMES = [
    n for n in CONSTANTS["CLASS_LABELS_BASE_NOVEL"] if n not in BASE_NAMES
]
CLASS_NAMES = BASE_NAMES + NOVEL_NAMES  # index 0..11 base, 12..56 novel
NUM_BASE = len(BASE_NAMES)
LABELS200 = list(CONSTANTS["CLASS_LABELS_200"])

# 200-class id -> unified GFS label (base 0..11, novel 12.., else -1/ignore)
LOOKUP = np.full(len(LABELS200), -1, dtype=np.int32)
for _i, _name in enumerate(LABELS200):
    if _name in CLASS_NAMES:
        LOOKUP[_i] = CLASS_NAMES.index(_name)


def convert_to_gfs(seg200):
    out = np.full(seg200.shape, -1, dtype=np.int32)
    valid = seg200 != -1
    out[valid] = LOOKUP[seg200[valid]]
    return out


def build_vlm(verbose=False):
    sys.path.insert(0, str(PLA))
    # GFS-VL ships softgroup_ops as source only; RegionPLC has a compiled
    # cp311 Windows build of the same op. Put it on the path so the shared
    # VFE import resolves.
    sg = REGIONPLC / "pcseg/external_libs/softgroup_ops"
    pool = REGIONPLC / "pcseg/ops/pool_by_idx"
    if sg.exists():
        sys.path.insert(0, str(sg))
    if pool.exists():
        sys.path.insert(0, str(pool))
    import softgroup_ops  # noqa: F401  (register the compiled extension)
    # pool_by_idx is only used by the caption head, which is disabled here.
    # RegionPLC ships a compiled cp311 build of the same op; alias it in so the
    # relative `from . import pool_by_idx` inside pcseg resolves.
    import importlib.util
    import types

    pool_pyd = pool / "pool_by_idx.cp311-win_amd64.pyd"
    if pool_pyd.exists() and "pcseg.ops.pool_by_idx.pool_by_idx" not in sys.modules:
        spec = importlib.util.spec_from_file_location(
            "pcseg.ops.pool_by_idx.pool_by_idx", str(pool_pyd)
        )
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        sys.modules["pcseg.ops.pool_by_idx.pool_by_idx"] = mod
    # pcseg/version.py is normally generated by setup.py; inject a stub so the
    # package imports without modifying the GFS-VL source tree.
    if "pcseg.version" not in sys.modules:
        version_mod = types.ModuleType("pcseg.version")
        version_mod.__version__ = "0.2.0+local"
        sys.modules["pcseg.version"] = version_mod

    # The instance head pulls in sklearn, but only its segmentation/task head is
    # exercised here. Mirror the lightweight stub used by RegionPLC's own
    # `regionplc_infer.py` instead of installing scikit-learn.
    if "sklearn" not in sys.modules:
        import importlib.machinery

        sk = types.ModuleType("sklearn")
        sk.__path__ = []
        sk.__spec__ = importlib.machinery.ModuleSpec("sklearn", None)
        sk_cluster = types.ModuleType("sklearn.cluster")
        sk_cluster.__path__ = []
        sk_cluster.__spec__ = importlib.machinery.ModuleSpec(
            "sklearn.cluster", None
        )
        sk_cluster.AgglomerativeClustering = lambda *a, **k: (_ for _ in ()).throw(
            NotImplementedError("sklearn stub: instance head unused")
        )
        sk.cluster = sk_cluster
        sys.modules["sklearn"] = sk
        sys.modules["sklearn.cluster"] = sk_cluster

    from pcseg.config import cfg, cfg_from_yaml_file, cfg_from_list
    from pcseg.models import build_vision_network, build_text_network
    from pcseg.models.text_networks import load_text_embedding_from_encoder

    # The PLA config resolves `_BASE_CONFIG_` and the text-embed path relative
    # to the working directory, and GFS-VL's own trainer loads it from the repo
    # root. Match that so the same yaml resolves identically.
    prev_cwd = os.getcwd()
    os.chdir(GFS)
    try:
        cfg_from_yaml_file(str(VLM_CFG), cfg)
    finally:
        os.chdir(prev_cwd)
    cfg.TAG = VLM_CFG.stem
    cfg.ROOT_DIR = str(PLA)
    cfg.DATA_CONFIG.DATA_PATH = str(PLA)
    cfg.CLASS_NAMES = CLASS_NAMES
    cfg_from_list(["TEXT_ENCODER.EXTRACT_EMBED", True], cfg)

    logger = logging.getLogger("vlm")
    logger.addHandler(logging.NullHandler())
    if verbose:
        logging.basicConfig(level=logging.INFO)

    # PLA's get_clip_model cannot load the CLIP archive under this environment:
    # the home path is non-ASCII (torch.jit.load -> errno 2) and its
    # `"visual.proj" in state_dict` check trips over the TorchScript state dict.
    # Load the identical official checkpoint from an ASCII copy and hand
    # build_model a plain dict.
    import clip as _clip_pkg
    import clip.model as _clip_model
    import pcseg.models.text_networks.text_models as _tm

    ascii_pt = Path(__file__).resolve().parent / "clip_cache/ViT-B-32.pt"

    def _get_clip_model(backbone_name):
        scripted = torch.jit.load(str(ascii_pt), map_location="cpu").eval()
        state_dict = {k: v for k, v in scripted.state_dict().items()}
        model = _clip_model.build_model(state_dict)
        return _clip_pkg.tokenize, model

    _tm.get_clip_model = _get_clip_model

    text_encoder = build_text_network(cfg.TEXT_ENCODER).cuda()
    text_embed = load_text_embedding_from_encoder(
        cfg.TEXT_ENCODER, text_encoder, logger
    )
    text_embed = text_embed.float()
    cfg.MODEL.TASK_HEAD.TEXT_EMBED.CHANNEL = text_embed.shape[1]
    cfg.MODEL.TASK_HEAD.TEXT_EMBED.NUM_CLASS = text_embed.shape[0]
    cfg.MODEL.TASK_HEAD.TEXT_EMBED.NORM = True
    cfg.MODEL.ADAPTER.TEXT_DIM = text_embed.shape[1]

    from easydict import EasyDict

    # GFS_VL_Trainer passes cfg.DATA_CONFIG itself as `dataset`; the task head
    # and VFE read IGNORE_LABEL / DATA_PROCESSOR / NUM_POINT_FEATURES off it.
    dataset = cfg.DATA_CONFIG
    dataset.setdefault("NUM_POINT_FEATURES", 6)
    model = build_vision_network(
        model_cfg=cfg.MODEL, num_class=CLASS_NAMES, dataset=dataset
    )
    ckpt = torch.load(str(CKPT), map_location="cpu", weights_only=False)
    state = ckpt.get("model_state", ckpt)
    state = {k.replace("module.", ""): v for k, v in state.items()}
    # The 636 checkpoint carries a 20-class `cls_head`; GFS-VL replaces it with
    # the CLIP text embedding via set_cls_head_with_text_embed below, so drop it
    # to avoid a shape-mismatch error during load.
    state = {k: v for k, v in state.items() if not k.startswith("task_head.cls_head.")}
    missing, unexpected = model.load_state_dict(state, strict=False)
    model.task_head.set_cls_head_with_text_embed(text_embed)
    model = model.cuda().eval()
    return cfg, model, text_embed, missing, unexpected


@torch.no_grad()
def vlm_forward(model, cfg, coord, color_u8, return_gpu=False):
    """return_gpu=True 时返回 GPU tensor，避免 400MB 的 H2D/D2H 往返。"""
    """coord (N,3) float32, color_u8 (N,3) 0-255. Returns feats (N,512), preds (N,)."""
    xyz = torch.as_tensor(coord, dtype=torch.float32, device="cuda")
    rgb = torch.as_tensor(color_u8, dtype=torch.float32, device="cuda") / 127.5 - 1.0

    voxel_scale = cfg.DATA_CONFIG.DATA_PROCESSOR.voxel_scale
    xyz_voxel = xyz * voxel_scale
    xyz_voxel = xyz_voxel - xyz_voxel.min(0).values
    indexed = torch.cat(
        [
            torch.zeros((xyz_voxel.shape[0], 1), dtype=torch.float32, device="cuda"),
            xyz_voxel,
        ],
        dim=-1,
    ).to(torch.int64)

    data = {
        "points_xyz": xyz,
        "rgb": rgb,
        "feats": torch.cat((rgb, xyz), dim=1),
        "points_xyz_voxel_scale": indexed,
        "batch_idxs": indexed[:, 0].to(torch.int32),
        "batch_size": 1,
        "offsets": torch.tensor([0, indexed.shape[0]], dtype=torch.int32),
        "spatial_shape": torch.clamp(
            indexed.max(0).values[1:] + 1, min=cfg.DATA_CONFIG.MIN_SPATIAL_SCALE
        ),
        "seg_labels": torch.full((xyz.shape[0],), -1, dtype=torch.int64, device="cuda"),
    }
    out = model(data)
    if return_gpu:
        return out["all_feats"], out["seg_preds"]
    return out["all_feats"].cpu().numpy(), out["seg_preds"].cpu().numpy()
